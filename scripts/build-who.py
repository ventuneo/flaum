#!/usr/bin/env python3
"""Turns the WHO anthro LMS tables into src/core/who-data.js (weekly rows, 0 to 24 months).

Usage: build-who.py <folder with weianthro.txt, lenanthro.txt, hcanthro.txt> <output.js>
"""
import csv
import json
import os
import sys

SOURCES = {'weight': 'weianthro.txt', 'length': 'lenanthro.txt', 'head': 'hcanthro.txt'}
MAX_AGE = 730


def main(folder, out):
    data = {}
    for metric, name in SOURCES.items():
        rows = {'m': [], 'f': []}
        with open(os.path.join(folder, name), encoding='utf-8') as handle:
            for row in csv.DictReader(handle, delimiter='\t'):
                age = int(row['age'])
                if age > MAX_AGE or not (age % 7 == 0 or age == MAX_AGE):
                    continue
                sex = 'm' if row['sex'] == '1' else 'f'
                rows[sex].append([age, float(row['l']), float(row['m']), float(row['s'])])
        data[metric] = rows
    body = json.dumps(data, separators=(',', ':'))
    with open(out, 'w', encoding='utf-8') as handle:
        handle.write('// WHO Child Growth Standards, LMS values by age in days (0 to 730).\n')
        handle.write('// Generated by scripts/build-who.py from the WHO anthro tables. Do not edit by hand.\n')
        handle.write(f'export const WHO = {body};\n')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
